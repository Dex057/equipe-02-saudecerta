CREATE TABLE age_consulta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL,
    profissional_id BIGINT NOT NULL,
    data_hora TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL,
    horario_ocupado TIMESTAMP,
    CONSTRAINT ck_age_consulta_status CHECK (status IN ('AGENDADA', 'REALIZADA', 'CANCELADA')),
    CONSTRAINT ck_age_consulta_horario_ocupado CHECK (
        (status = 'AGENDADA' AND horario_ocupado = data_hora)
        OR (status <> 'AGENDADA' AND horario_ocupado IS NULL)
    ),
    CONSTRAINT uk_consulta_profissional_horario_ocupado UNIQUE (profissional_id, horario_ocupado)
);
