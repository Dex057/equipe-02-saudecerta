-- Módulo seguranca.auditoria (prefixo aud_). Convenções e privilégios: ADR-006.
-- Trilha imutável: em produção a aplicação só tem SELECT e INSERT nesta tabela (nunca UPDATE ou DELETE).

CREATE TABLE aud_registro_auditoria (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo        VARCHAR(20)  NOT NULL,
    paciente_id BIGINT,
    usuario_id  BIGINT,
    acao        VARCHAR(60)  NOT NULL,
    detalhe     VARCHAR(500),
    data_hora   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Consulta da trilha por paciente e período (RF12).
CREATE INDEX idx_aud_registro_paciente_data ON aud_registro_auditoria (paciente_id, data_hora);
