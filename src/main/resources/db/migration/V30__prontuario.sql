
-- E3 - Prontuario eletronico
-- Migracao do modulo prontuario (ADR-006)

CREATE TABLE pro_prontuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL UNIQUE
);

CREATE TABLE pro_atendimento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prontuario_id BIGINT NOT NULL,
    consulta_id BIGINT NOT NULL UNIQUE,
    queixa VARCHAR(4000) NOT NULL,
    evolucao VARCHAR(4000) NOT NULL,
    conduta VARCHAR(4000) NOT NULL,
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_pro_atendimento_prontuario
        FOREIGN KEY (prontuario_id)
        REFERENCES pro_prontuario(id)
);

CREATE TABLE pro_complemento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atendimento_id BIGINT NOT NULL,
    profissional_id BIGINT NOT NULL,
    texto VARCHAR(4000) NOT NULL,
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_pro_complemento_atendimento
        FOREIGN KEY (atendimento_id)
        REFERENCES pro_atendimento(id)
);

CREATE TABLE pro_prescricao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atendimento_id BIGINT NOT NULL,
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_pro_prescricao_atendimento
        FOREIGN KEY (atendimento_id)
        REFERENCES pro_atendimento(id)
);

CREATE TABLE pro_item_prescricao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescricao_id BIGINT NOT NULL,
    medicamento VARCHAR(255) NOT NULL,
    dosagem VARCHAR(255) NOT NULL,
    posologia VARCHAR(500) NOT NULL,
    duracao VARCHAR(255) NOT NULL,

    CONSTRAINT fk_pro_item_prescricao
        FOREIGN KEY (prescricao_id)
        REFERENCES pro_prescricao(id)
);

CREATE TABLE pro_solicitacao_exame (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atendimento_id BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'SOLICITADO',

    CONSTRAINT fk_pro_exame_atendimento
        FOREIGN KEY (atendimento_id)
        REFERENCES pro_atendimento(id),

    CONSTRAINT ck_pro_exame_status
        CHECK (status IN (
            'SOLICITADO', 'REALIZADO', 'CANCELADO'
        ))
);

CREATE INDEX idx_pro_atendimento_historico
    ON pro_atendimento(prontuario_id, data_hora DESC);

CREATE INDEX idx_pro_complemento_atendimento
    ON pro_complemento(atendimento_id);

CREATE INDEX idx_pro_exame_atendimento
    ON pro_solicitacao_exame(atendimento_id);
