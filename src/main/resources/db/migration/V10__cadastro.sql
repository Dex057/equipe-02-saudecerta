-- Módulo cadastro (prefixo cad_). Convenções e privilégios: ADR-006.

CREATE TABLE cad_especialidade (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL,
    CONSTRAINT uk_cad_especialidade_nome UNIQUE (nome)
);

-- cpf_ativo repete o CPF enquanto o paciente está ativo e fica NULL quando inativo.
-- O UNIQUE impede dois ativos com o mesmo CPF (RN01); NULLs não colidem.
CREATE TABLE cad_paciente (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(120) NOT NULL,
    nome_normalizado VARCHAR(120) NOT NULL,
    cpf              VARCHAR(11)  NOT NULL,
    cpf_ativo        VARCHAR(11),
    data_nascimento  DATE         NOT NULL,
    telefone         VARCHAR(20),
    email            VARCHAR(120),
    ativo            BOOLEAN      NOT NULL,
    CONSTRAINT uk_cad_paciente_cpf_ativo UNIQUE (cpf_ativo)
);

-- Busca por prefixo do nome (RNF03).
CREATE INDEX idx_cad_paciente_nome ON cad_paciente (nome_normalizado);

CREATE TABLE cad_profissional (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(120) NOT NULL,
    ativo BOOLEAN      NOT NULL
);

-- Ligação profissional x especialidade (RF02). Só SELECT, INSERT e DELETE em produção.
CREATE TABLE cad_profissional_especialidade (
    profissional_id  BIGINT NOT NULL,
    especialidade_id BIGINT NOT NULL,
    PRIMARY KEY (profissional_id, especialidade_id),
    CONSTRAINT fk_cad_prof_esp_profissional  FOREIGN KEY (profissional_id)  REFERENCES cad_profissional (id),
    CONSTRAINT fk_cad_prof_esp_especialidade FOREIGN KEY (especialidade_id) REFERENCES cad_especialidade (id)
);
